// Writes src/world.d.ts: types for every instance in world/, so code can use `Workspace.SpawnLocation`
// with autocomplete. Generated from Rojo's sourcemap of world/default.project.json; never edit it.
import { execFileSync } from "node:child_process";
import fs from "node:fs";

const OUTPUT = "src/world.d.ts";
const sourcemap = JSON.parse(
	execFileSync("rojo", ["sourcemap", "world/default.project.json", "--include-non-scripts"], {
		encoding: "utf8",
	}),
);

const key = (name) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : JSON.stringify(name));

// An instance's type: its class, plus each child by name. Duplicate names can't be typed: skip them.
function typeOf(node, indent) {
	const children = (node.children ?? []).filter(
		(child, _, all) => all.filter((other) => other.name === child.name).length === 1,
	);
	if (children.length === 0) return node.className;
	const fields = children.map((child) => `${indent}\t${key(child.name)}: ${typeOf(child, `${indent}\t`)};`);
	return `${node.className} & {\n${fields.join("\n")}\n${indent}}`;
}

const services = (sourcemap.children ?? [])
	.filter((service) => (service.children ?? []).length > 0)
	.map((service) => {
		const body = typeOf(service, "");
		const fields = body.slice(body.indexOf("{") + 1, body.lastIndexOf("}"));
		return `\tinterface ${service.className} {${fields.replaceAll("\n", "\n\t")}}`;
	});

const header =
	"// Generated by scripts/world-types.mjs from world/. Don't edit: change world/ and run `mise run check`.\n";
fs.writeFileSync(OUTPUT, `${header}\ndeclare global {\n${services.join("\n\n")}\n}\n\nexport {};\n`);
